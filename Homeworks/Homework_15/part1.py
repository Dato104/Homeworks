

class Dog:
    def __init__(self, name, age):
        self.name = name
        self.age = age

    def bark(self):
        print(f"{self.name} says: Woof!")

    def info(self):
        print(f"{self.name} is {self.age} years old")

dog_1 = Dog("Bob", 18)

dog_1.bark()
dog_1.info()






















































